#!/usr/bin/env node
// build/generate-cid.mjs — stamp CID digest into shared/generated-cid.js from cid.template.json

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = join(root, 'shared', 'cid.template.json');
const outPath = join(root, 'shared', 'generated-cid.js');

const raw = readFileSync(templatePath, 'utf8');
const template = JSON.parse(raw);

// Canonical-ish: stable JSON for hashing (sorted keys shallow + ops)
function stableStringify(obj) {
  if (obj === null || typeof obj !== 'object') return JSON.stringify(obj);
  if (Array.isArray(obj)) return `[${obj.map(stableStringify).join(',')}]`;
  const keys = Object.keys(obj).sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${stableStringify(obj[k])}`).join(',')}}`;
}

const digest = createHash('sha256').update(stableStringify(template)).digest('hex');
const cid = {
  ...template,
  digest: `sha256:${digest}`,
  generatedAt: new Date().toISOString(),
};

const js = `// AUTO-GENERATED by build/generate-cid.mjs — do not edit
export const CID = ${JSON.stringify(cid, null, 2)};
export default CID;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, js);
console.log(`generate-cid: wrote ${outPath} digest=sha256:${digest.slice(0, 12)}…`);
