import * as vscode from 'vscode';
import * as path from 'path';
import * as fs from 'fs';
import type { JourneyStateService } from './state';

/** Write a real document under .threedot/artifacts and open it. */
export async function writeArtifact(
  svc: JourneyStateService,
  key: string,
  filename: string,
  content: string,
  kind: string
): Promise<string | undefined> {
  const ws = vscode.workspace.workspaceFolders?.[0];
  if (!ws) {
    void vscode.window.showWarningMessage('3dot journey: open a folder first.');
    return undefined;
  }
  const dir = path.join(ws.uri.fsPath, '.threedot', 'artifacts');
  fs.mkdirSync(dir, { recursive: true });
  const full = path.join(dir, filename);
  fs.writeFileSync(full, content, 'utf8');
  svc.addArtifact(key, full, kind, content);
  const doc = await vscode.workspace.openTextDocument(full);
  await vscode.window.showTextDocument(doc, { preview: true, viewColumn: vscode.ViewColumn.Beside });
  return full;
}

