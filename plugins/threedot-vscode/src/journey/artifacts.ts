export function cpcpPodYaml(title: string): string {
  return `# cpcp.pod.yaml — four-role boundary (reviewable)
# Preflight: no in-process jobs; FRONT/BACK role separation
apiVersion: cpcp/v1
kind: Pod
metadata:
  name: ${slug(title) || 'cpcp-pod'}
  labels:
    threedot.dev/journey: "true"
spec:
  roles:
    - name: FRONT
      image: cpcp/front:latest
      ports: [8080]
    - name: BACK
      image: cpcp/back:latest
      ports: [8081]
      env:
        CID_PATH: /_cpcp/cid.json
    - name: BackJob
      image: cpcp/backjob:latest
      # async only — never in-process with FRONT
    - name: GRAPH
      image: cpcp/graph:latest
  edges:
    - from: FRONT
      to: BACK
      protocol: json-rpc-ld
    - from: BACK
      to: BackJob
      protocol: queue
    - from: BACK
      to: GRAPH
      protocol: sparql
  preflight:
    noInProcessJobs: true
    cidBound: true
`;
}

