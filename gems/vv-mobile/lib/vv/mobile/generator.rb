      def swift_enum_case(name)
        core = name.sub(/\Atask\./, "")
        parts = core.split(/[^A-Za-z0-9]+/)
        return core if parts.empty?
        first = parts[0]
        rest = parts.drop(1).map { |p| p.capitalize }
        (first[0].downcase + first[1..] + rest.join)
      end

      def identifiable_suffix(props)
        props.any? { |p| p["name"] == "id" } ? ", Identifiable" : ""
      end

      def sample_json_pair(prop)
        type = prop["type"].to_s
        value = case type
                when "Int", "Int64", "Double" then "1"
                when "Bool" then "true"
                else "\\\"sample\\\""
                end
        "\\\"#{prop["name"]}\\\": #{value}"
      end
    end
