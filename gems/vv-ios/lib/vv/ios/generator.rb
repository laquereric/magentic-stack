require "fileutils"
require "vv/mobile"

module Vv
  module Ios
    # Emits a SwiftUI iOS app that *consumes* the vv-mobile SharedKit package.
    # SwiftUI is legal here — this target never builds for Android.
    class Generator
      PACKAGE_DIR = "IosApp"

      def initialize(spec:, output_dir:)
        @spec = spec
        @output_dir = output_dir
      end

      def generate
        root = File.join(@output_dir, PACKAGE_DIR)
        sources = File.join(root, "Sources", PACKAGE_DIR)
        FileUtils.mkdir_p(File.join(sources, "Views"))
        FileUtils.mkdir_p(File.join(sources, "ViewModels"))
        FileUtils.mkdir_p(File.join(sources, "Acia"))

        written = []
        written << write(File.join(root, "Package.swift"), package_swift)
        written << write(File.join(root, "README.md"), package_readme)
        written << write(File.join(sources, "#{PACKAGE_DIR}App.swift"), app_swift)
        written << write(File.join(sources, "Acia", "AciaViews.swift"), acia_views_swift)
        written << write(File.join(sources, "Acia", "AciaRenderer.swift"), acia_renderer_swift)
        written << write(File.join(sources, "Acia", "TaskSlotView.swift"), task_slot_swift)
        written << write(File.join(sources, "Acia", "CatalogGalleryView.swift"), catalog_gallery_swift)
        @spec.models.each do |model|
          written << write(File.join(sources, "ViewModels", "#{model["name"]}ListModel.swift"), list_model_swift(model))
          written << write(File.join(sources, "Views", "#{model["name"]}ListView.swift"), list_view_swift(model))
          written << write(File.join(sources, "Views", "#{model["name"]}DetailView.swift"), detail_view_swift(model))
        end

        { ok: true, written: written.sort, count: written.size, package_dir: root }
      rescue SystemCallError => e
        { ok: false, reason: "io_error", because: e.message }
      end

      private

      def write(path, contents)
        FileUtils.mkdir_p(File.dirname(path))
        File.write(path, contents)
        path
      end

      def header(note)
        <<~SWIFT
          // Generated by vv-ios #{Vv::Ios::VERSION}. Do not edit by hand.
          // #{note}
          #{Vv::Mobile::Copyright::SWIFT}

        SWIFT
      end

      def kit
        @spec.module_name
      end

      def repo_for(model)
        @spec.repositories.find { |r| r["model"] == model["name"] }
      end

      def package_swift
        <<~SWIFT
          // swift-tools-version: 6.3
          #{Vv::Mobile::Copyright::SWIFT}
          // Generated by vv-ios #{Vv::Ios::VERSION}.
          // iOS / macOS SwiftUI shell. Depends on the vv-mobile shared package.
          // Apple-only — SwiftUI has no renderer on the official Swift SDK for Android.

          import PackageDescription

          let package = Package(
              name: "#{PACKAGE_DIR}",
              platforms: [
                  .iOS(.v17),
                  .macOS(.v14)
              ],
              products: [
                  .library(name: "#{PACKAGE_DIR}", targets: ["#{PACKAGE_DIR}"])
              ],
              dependencies: [
                  .package(path: "../#{kit}")
              ],
              targets: [
                  .target(
                      name: "#{PACKAGE_DIR}",
                      dependencies: [
                          .product(name: "#{kit}", package: "#{kit}")
                      ]
                  )
              ]
          )
        SWIFT
      end

      def package_readme
        <<~MD
          # #{PACKAGE_DIR}

          Generated by **vv-ios** #{Vv::Ios::VERSION}. SwiftUI shell over
          `#{kit}` (emitted by vv-mobile).

          This package is **Apple-only**. Android UI is Kotlin/Compose calling
          into the shared `.so` via `vv-android` — not SwiftUI, not Skip.

          ```bash
          # emit shared kit first
          vv-mobile generate spec.yml ./out
          vv-ios generate spec.yml ./out
          swift build --package-path out/IosApp
          ```
        MD
      end

      def app_swift
        first = @spec.models.first
        app_tab = first ? "#{first["name"]}ListView()" : "Text(\"#{kit}\")"
        header("SwiftUI @main. Precompiled 12 AIUX + 19 ACIA live in Catalog + TaskSlot tabs.") + <<~SWIFT
          import SwiftUI
          import #{kit}

          @main
          struct #{PACKAGE_DIR}App: App {
              var body: some Scene {
                  WindowGroup {
                      TabView {
                          NavigationStack { #{app_tab} }
                              .tabItem { Label("App", systemImage: "iphone") }
                          NavigationStack { CatalogGalleryView() }
                              .tabItem { Label("Catalog", systemImage: "square.grid.2x2") }
                          NavigationStack { TaskSlotView() }
                              .tabItem { Label("Task", systemImage: "checklist") }
                      }
                  }
              }
          }
        SWIFT
      end

      def acia_views_swift
        views = Vv::Mobile::Catalog::ACIA_COMPONENTS.map { |kind| acia_view_for(kind) }.join("\n")
        header("Precompiled SwiftUI for all 19 ghis-19@1 ACIA components.") + <<~SWIFT
          import SwiftUI
          import #{kit}

          #{views}
        SWIFT
      end

