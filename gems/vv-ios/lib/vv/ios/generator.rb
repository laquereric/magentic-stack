      def acia_renderer_swift
        cases = Vv::Mobile::Catalog::ACIA_COMPONENTS.map { |kind|
          "            case #{kind.inspect}: #{kind}View(node: node)"
        }.join("\n")
        header("Dispatch ACIA node → precompiled SwiftUI widget. Unknown kind is RefusalNotice.") + <<~SWIFT
          import SwiftUI
          import #{kit}

          public struct AciaRenderer: View {
              public let node: AciaNode
              public init(node: AciaNode) { self.node = node }

              public var body: some View {
                  switch node.componentKind {
          #{cases}
                  default:
                      RefusalNoticeView(node: AciaNode(
                          nodeId: "unknown",
                          componentKind: "RefusalNotice",
                          value: ["reason": "kind_not_in_catalog", "operation": node.componentKind]
                      ))
                  }
              }
          }

          public struct AciaChildrenView: View {
              public let nodes: [AciaNode]
              public init(nodes: [AciaNode]) { self.nodes = nodes }
              public var body: some View {
                  ForEach(nodes, id: \\.nodeId) { child in
                      AciaRenderer(node: child)
                  }
              }
          }
        SWIFT
      end

      def task_slot_swift
        header("Task overlay. Compiles a named AIUX intention into ghis-19 and draws it.") + <<~SWIFT
          import SwiftUI
          import #{kit}

          public struct TaskSlotView: View {
              @State private var kind: AiuxIntention = .empty
              @State private var document: AciaDocument?
              @State private var failure: Failure?

              public init() {}

              public var body: some View {
                  VStack(alignment: .leading, spacing: 12) {
                      Picker("Intention", selection: $kind) {
                          ForEach(AiuxIntention.allCases, id: \\.self) { item in
                              Text(item.rawValue).tag(item)
                          }
                      }
                      .onChange(of: kind) { _, _ in compile() }
                      if let failure {
                          ContentUnavailableView(failure.reason, systemImage: "xmark.octagon",
                                                 description: Text(failure.because))
                      } else if let document {
                          AciaRenderer(node: document.root)
                      }
                  }
                  .padding()
                  .navigationTitle("Task slot")
                  .onAppear { compile() }
              }

              private func compile() {
                  var request = AiuxCompileRequest(taskKind: kind.rawValue)
                  if kind == .form {
                      request.fields = [["name": "decision", "datatype": "enum"]]
                  }
                  if kind == .preview {
                      request.blobDigest = "sha256:" + String(repeating: "ab", count: 32)
                  }
                  switch AiuxCompiler.compile(request) {
                  case .ok(let doc):
                      document = doc
                      failure = nil
                  case .fail(let f):
                      document = nil
                      failure = f
                  }
              }
          }
        SWIFT
      end

