      def list_model_swift(model)
        name = model["name"]
        repo = repo_for(model)
        repo_type = repo ? repo["name"] : "#{name}Repository"
        header("@MainActor ObservableObject wrapping the shared actor repository.") + <<~SWIFT
          import Foundation
          import Observation
          import #{kit}

          @Observable
          @MainActor
          public final class #{name}ListModel {
              public var items: [#{name}] = []
              public var failure: Failure?
              public var loading = false
              private let repository: #{repo_type}

              public init(repository: #{repo_type}) {
                  self.repository = repository
              }

              public func load() async {
                  loading = true
                  defer { loading = false }
                  switch await repository.list() {
                  case .ok(let items):
                      self.items = items
                      self.failure = nil
                  case .fail(let failure):
                      self.failure = failure
                  }
              }
          }
        SWIFT
      end

      def list_view_swift(model)
        name = model["name"]
        props = @spec.properties_for(model)
        title_prop = props.find { |p| p["name"] == "name" } || props.first
        subtitle_prop = props.find { |p| p["name"] == "id" }
        title_expr = title_prop ? "item.#{title_prop["name"]}" : "String(describing: item)"
        subtitle = subtitle_prop ? "Text(item.#{subtitle_prop["name"]}).font(.caption).foregroundStyle(.secondary)" : ""
        repo = repo_for(model)
        repo_type = repo ? repo["name"] : "#{name}Repository"
        header("SwiftUI list. Consumes SharedKit Envelope — never unwraps throws.") + <<~SWIFT
          import SwiftUI
          import #{kit}

          public struct #{name}ListView: View {
              @State private var model: #{name}ListModel

              public init() {
                  _model = State(initialValue: #{name}ListModel(repository: #{repo_type}()))
              }

              public var body: some View {
                  Group {
                      if model.loading && model.items.isEmpty {
                          ProgressView()
                      } else if let failure = model.failure, model.items.isEmpty {
                          ContentUnavailableView(
                              failure.reason,
                              systemImage: "exclamationmark.triangle",
                              description: Text(failure.because)
                          )
                      } else {
                          List(model.items) { item in
                              NavigationLink {
                                  #{name}DetailView(item: item)
                              } label: {
                                  VStack(alignment: .leading) {
                                      Text(#{title_expr})
                                      #{subtitle}
                                  }
                              }
                          }
                      }
                  }
                  .navigationTitle("#{name}s")
                  .task { await model.load() }
                  .refreshable { await model.load() }
              }
          }
        SWIFT
      end

      def detail_view_swift(model)
        name = model["name"]
        rows = @spec.properties_for(model).map do |p|
          "                LabeledContent(#{p["name"].inspect}) { Text(String(describing: item.#{p["name"]})) }"
        end.join("\n")
        header("SwiftUI detail. Read-only projection of a shared model.") + <<~SWIFT
          import SwiftUI
          import #{kit}

          public struct #{name}DetailView: View {
              public let item: #{name}

              public init(item: #{name}) {
                  self.item = item
              }

              public var body: some View {
                  Form {
          #{rows}
                  }
                  .navigationTitle("#{name}")
              }
          }
        SWIFT
      end
